export function message(key, params = {}, lang = 'ru') {
  const s = MESSAGES[lang]?.[key] ?? MESSAGES.ru[key];
  if (s === undefined) throw new Error(`Нет сообщения: ${key}`);
  return fmt(s, params);
}
